#!/usr/bin/env python3
"""Render the kgateway-crds chart and bound every CEL-validated string/array so the CRDs pass
the API server's CEL cost budget (ADR 0010).

Kubernetes 1.36 rejects four kgateway v2.3.x/v2.4.x CRDs with "estimated rule cost exceeds
budget by factor of 4.0x (try ... adding maxItems, maxProperties, and maxLength ...)". The rules
are on duration strings and small arrays; bounding them changes nothing in practice. Re-run
when bumping kgateway:

    python3 scripts/kgateway-crds-patch.py v2.3.1 > gitops/platform/kgateway-crds/crds.yaml

Requires helm and PyYAML. Verify with
    kubectl apply --server-side --dry-run=server -f gitops/platform/kgateway-crds/crds.yaml
"""
import subprocess, sys, yaml

MAX_LENGTH = 256   # durations/names are far shorter; the bound only caps the cost estimate
MAX_ITEMS = 64

def walk(node, fn):
    if not isinstance(node, dict):
        return
    fn(node)
    for v in (node.get("properties") or {}).values():
        walk(v, fn)
    if isinstance(node.get("items"), dict):
        walk(node["items"], fn)
    if isinstance(node.get("additionalProperties"), dict):
        walk(node["additionalProperties"], fn)

def bound(node):
    if not node.get("x-kubernetes-validations"):
        return
    if node.get("type") == "string" and "maxLength" not in node and "enum" not in node:
        node["maxLength"] = MAX_LENGTH
    if node.get("type") == "array" and "maxItems" not in node:
        node["maxItems"] = MAX_ITEMS

def main(version):
    out = subprocess.run(
        ["helm", "template", "kgateway-crds", "oci://cr.kgateway.dev/kgateway-dev/charts/kgateway-crds", "--version", version],
        check=True, capture_output=True, text=True).stdout
    docs = [d for d in yaml.safe_load_all(out) if d]
    for d in docs:
        for v in d["spec"]["versions"]:
            walk(v["schema"]["openAPIV3Schema"], bound)
    sys.stdout.write(f"# GENERATED by scripts/kgateway-crds-patch.py {version}; do not edit by hand.\n")
    sys.stdout.write(yaml.safe_dump_all(docs, sort_keys=False))

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "v2.3.1")
